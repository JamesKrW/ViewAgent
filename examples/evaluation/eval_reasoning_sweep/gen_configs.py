#!/usr/bin/env python3
"""Generate per-model reasoning-sweep configs + smoke configs + run script.

Modes:
  nothink -> defaults: [eval_nothink]   (tuned no-think prompt, reasoning off)
  high    -> defaults: [eval_high]      (eval_mode prompt, reasoning effort=high)

The "medium" mode is NOT generated: it is identical to the published
eval_all_openrouter baseline (eval_mode + reasoning.effort=medium), whose
numbers we reuse from the paper table rather than re-running.
"""
from __future__ import annotations
import copy
from pathlib import Path

from omegaconf import OmegaConf

HERE = Path(__file__).resolve().parent

MODELS = {
    "gpt_5_4":        "openai/gpt-5.4",
    "gemini_3_1_pro": "google/gemini-3.1-pro-preview",
    "claude_opus_4_6":"anthropic/claude-opus-4.6",
    "grok_4_20_beta": "x-ai/grok-4.20-beta",
}
MODES = ["nothink", "high"]

# Per-model reasoning config for the "nothink" mode. Most providers accept a
# hard reasoning OFF; Gemini 3.1 Pro mandates reasoning (rejects enabled:false
# and ignores tiny budgets, ~190 min reasoning tokens), so its "nothink" is the
# minimum available effort. Documented as a caveat in the final report.
NOTHINK_REASONING = {
    "gpt_5_4":         {"enabled": False},
    "claude_opus_4_6": {"enabled": False},
    "grok_4_20_beta":  {"enabled": False},
    "gemini_3_1_pro":  {"effort": "low"},   # cannot fully disable reasoning
}

HEADER = "# AUTO-GENERATED by gen_configs.py — edit eval_<mode>.yaml or this script, not this file.\n"


def write_model_configs():
    for mode in MODES:
        for name, model_id in MODELS.items():
            cfg = {
                "defaults": [f"eval_{mode}"],
                "experiment": {
                    "dump_dir": f"${{fileroot}}/rollouts/reasoning_sweep/{mode}/{name}",
                    "default_max_turns": 1,
                },
                "backends": {"openai": {"model": model_id}},
            }
            if mode == "nothink":
                cfg["default_chat_config"] = {
                    "extra_body": {"reasoning": NOTHINK_REASONING[name]}
                }
            out = HERE / f"{mode}_{name}.yaml"
            out.write_text(HEADER + OmegaConf.to_yaml(OmegaConf.create(cfg)))
            print("wrote", out.name)


def write_smoke_configs():
    """Self-contained (no defaults) so we can shrink n_envs to 2/env."""
    for mode in MODES:
        base = OmegaConf.load(HERE / f"eval_{mode}.yaml")
        cfg = OmegaConf.to_container(base, resolve=False)
        for env in cfg["envs"]:
            env["n_envs"] = 2
            env["seed"] = [1, 4, 1]  # 2 tiny deterministic samples
        cfg["experiment"]["dump_dir"] = f"${{fileroot}}/rollouts/reasoning_sweep/_smoke/{mode}_gpt_5_4"
        cfg["run"]["max_concurrent_jobs"] = 4
        cfg["backends"]["openai"]["model"] = MODELS["gpt_5_4"]
        cfg["backends"]["openai"]["max_concurrency"] = 4
        if mode == "nothink":
            cfg["default_chat_config"]["extra_body"] = {"reasoning": NOTHINK_REASONING["gpt_5_4"]}
        out = HERE / f"smoke_{mode}_gpt_5_4.yaml"
        out.write_text(HEADER + OmegaConf.to_yaml(OmegaConf.create(cfg)))
        print("wrote", out.name)


if __name__ == "__main__":
    write_model_configs()
    write_smoke_configs()
